/* Structure of Doubly Linked List Node
class Node {
  public:
    int data;
    Node *next;
    Node *prev;

    Node(int val) {
        data = val;
        next = nullptr;
        prev = nullptr;
    }
};

*/
class Solution {
  public:
    Node *reverse(Node *head) {
        // code here
        Node* temp=head;
        
        while(temp!=NULL){
            Node* prev=temp->prev;
            temp->prev=temp->next;
            temp->next=prev;
            head=temp;
            temp=temp->prev;    
            
        }
        return head;     
    }
};

